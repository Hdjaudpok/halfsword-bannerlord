"""Build the HalfSwordCombat physics profile from the player's own Half Sword extraction.

    python make_profile.py [<halfsword-decomp folder>]   (default: %USERPROFILE%\\halfsword-decomp)

Reads   dumps/pass1/willie_capsules.txt (physics asset: bodies, constraints, Motor profiles)
        dumps/pass2/masses.txt          (GetBoneMass per body)
Writes  port/hs_profile.txt             (one record per line, key=value tokens; read by the mod at load time)

Nothing from Half Sword is stored in the mod or its repository: this converter runs on the player's machine.
Half Sword bodies are merged onto Bannerlord's human_skeleton (fewer spine/neck bones): masses add up, joint ranges
of merged joints add up (the chain keeps its total flexibility), drive stiffness takes the maximum.
"""
import os
import re
import sys

ROOT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.expanduser("~"), "halfsword-decomp")

# Bannerlord body -> (Half Sword bodies, Bannerlord parent body). Joint of a body = constraints of its HS bodies.
MAP = [
    ("pelvis", ["pelvis"], None),
    ("spine", ["spine_02"], "pelvis"),
    ("spine1", ["spine_03"], "spine"),
    ("spine2", ["spine_04", "spine_05"], "spine1"),
    ("neck", ["neck_01", "neck_02"], "spine2"),
    ("head", ["Head"], "neck"),
]
for side in ("l", "r"):
    MAP += [
        ("%s_clavicle" % side, ["clavicle_%s" % side], "spine2"),
        ("%s_upperarm_twist" % side, ["upperarm_%s" % side], "%s_clavicle" % side),
        ("%s_foretwist" % side, ["lowerarm_%s" % side], "%s_upperarm_twist" % side),
        ("%s_hand" % side, ["hand_%s" % side], "%s_foretwist" % side),
        ("%s_thigh" % side, ["thigh_%s" % side], "pelvis"),
        ("%s_calf" % side, ["calf_%s" % side], "%s_thigh" % side),
        ("%s_foot" % side, ["foot_%s" % side], "%s_calf" % side),
    ]
HINGES = {"l_foretwist", "r_foretwist", "l_calf", "r_calf"}  # elbows and knees bend one way

NUM = r"(-?[\d.]+)"


def parse_asset(path):
    bodies, constraints = {}, []
    cur = None
    for line in open(path, encoding="utf-8"):
        m = re.match(r"\s+body\[\d+\] bone=(\S+)", line)
        if m:
            b = {"bone": m.group(1)}
            s = re.search(r"sphyl\[r=%s len=%s" % (NUM, NUM), line)
            if s:
                b.update(shape="capsule", radius=float(s.group(1)), length=float(s.group(2)))
            x = re.search(r"box\[x=%s y=%s z=%s" % (NUM, NUM, NUM), line)
            if x and "shape" not in b:
                b.update(shape="box", box=(float(x.group(1)), float(x.group(2)), float(x.group(3))))
            sp = re.search(r"sphere\[r=%s" % NUM, line)
            if sp and b.get("shape") == "capsule":
                b["radius"] = max(b["radius"], float(sp.group(1)))  # Head: capsule + sphere
            d = re.search(r"linDamp=%s angDamp=%s" % (NUM, NUM), line)
            if d:
                b.update(lin_damp=float(d.group(1)), ang_damp=float(d.group(2)))
            bodies[b["bone"]] = b
            continue
        m = re.match(r"\s+constraint\[\d+\] joint=(\S+) bone1=(\S+) bone2=(\S+)", line)
        if m:
            cur = {"joint": m.group(1), "child": m.group(2), "parent": m.group(3)}
            constraints.append(cur)
            continue
        m = re.match(r"\s+profile (\w+):(.*)", line)
        if m and cur is not None:
            cur.setdefault("profiles", {})[m.group(1)] = m.group(2)
    return bodies, constraints


def limits_and_drive(text):
    g = lambda pat: re.search(pat, text)
    s1 = float(g(r"swing1=\d/%s" % NUM).group(1))
    s2 = float(g(r"swing2=\d/%s" % NUM).group(1))
    tw = float(g(r"twist=\d/%s" % NUM).group(1))
    soft = g(r"coneSoft=\w+ k=%s d=%s" % (NUM, NUM))
    ks = [float(k) for k in re.findall(r"(?:swing|twist)\[pos=true vel=\w+ k=%s" % NUM, text)]
    ds = [float(k) for k in re.findall(r"(?:swing|twist)\[pos=true vel=\w+ k=[\d.]+ d=%s" % NUM, text)]
    return s1, s2, tw, (float(soft.group(1)), float(soft.group(2))) if soft else (0, 0), max(ks) if ks else 0.0, max(ds) if ds else 0.0


def main():
    bodies, constraints = parse_asset(os.path.join(ROOT, "dumps", "pass1", "willie_capsules.txt"))
    masses = {}
    for line in open(os.path.join(ROOT, "dumps", "pass2", "masses.txt"), encoding="utf-8"):
        parts = line.strip().split("\t")
        if len(parts) == 2 and parts[0] != "TOTAL":
            masses[parts[0]] = float(parts[1])
    # The UserConstraint_* duplicates carry the limits and motors (the anatomical ones are free / k=0).
    user = {c["child"]: c for c in constraints if c["joint"].startswith("UserConstraint")}

    out = ["# HalfSwordCombat physics profile, generated by tools/halfsword/make_profile.py from the local Half Sword",
           "# extraction. Personal use: do not commit or share this file. Units: metres, kilograms, degrees."]
    total = 0.0
    for bl, hs, parent in MAP:
        mass = sum(masses[b] for b in hs)
        total += mass
        shapes = [bodies[b] for b in hs]
        lin = shapes[0].get("lin_damp", 0.01)
        ang = shapes[0].get("ang_damp", 10.0)
        if all(s.get("shape") == "box" for s in shapes):
            bx = shapes[0]["box"]
            shape = "box=%.4f,%.4f,%.4f" % (bx[0] / 100, bx[1] / 100, bx[2] / 100)
        else:
            shape = "radius=%.4f" % (max(s.get("radius", 5.0) for s in shapes) / 100)
        out.append("body %s mass=%.4f %s lin_damp=%.4f ang_damp=%.4f hs=%s" % (bl, mass, shape, lin, ang, "+".join(hs)))
        if parent is None:
            continue
        s1 = s2 = tw = 0.0
        k = d = sk = sd = 0.0
        for b in hs:
            c = user.get(b)
            if c is None or "Motor" not in c.get("profiles", {}):
                continue
            a1, a2, at, soft, kk, dd = limits_and_drive(c["profiles"]["Motor"])
            s1, s2, tw = s1 + a1, s2 + a2, tw + at
            k, d = max(k, kk), max(d, dd)
            sk, sd = soft
        out.append("joint %s parent=%s swing1=%.1f swing2=%.1f twist=%.1f motor_k=%.1f motor_d=%.2f limit_k=%.1f limit_d=%.1f%s" % (
            bl, parent, s1, s2, tw, k, d, sk, sd, " hinge=1" if bl in HINGES else ""))
    # Muscles and balance: values read in game (physical animation settings, PhysicsHandle hooks and CDO defaults).
    out.append("muscles orientation=1000 angular_velocity=100 max_angular=5000 max_linear=100 acceleration_mode=1")
    out.append("handle name=lower bone=pelvis linear_k=1000 linear_d=200 angular_k=1000 angular_d=500")
    out.append("handle name=upper bone=spine2 linear_k=100 linear_d=200 angular_k=0 angular_d=0")
    out.append("# total mass %.3f kg" % total)

    os.makedirs(os.path.join(ROOT, "port"), exist_ok=True)
    path = os.path.join(ROOT, "port", "hs_profile.txt")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", path)
    print("\n".join(out))


if __name__ == "__main__":
    main()
